Point = tuple[float, float]


class Outline:
    """Closed contours of line, quadratic and cubic segments (font units, y up)."""

    def __init__(self, contours=None):
        self.contours: list[list[tuple]] = contours or []

    def map(self, f) -> "Outline":
        out = []
        for contour in self.contours:
            seg_out = []
            for seg in contour:
                op, pts = seg[0], seg[1:]
                seg_out.append((op, *[f(p) for p in pts]))
            out.append(seg_out)
        return Outline(out)

    def moved(self, dx: float, dy: float = 0.0) -> "Outline":
        return self.map(lambda p: (p[0] + dx, p[1] + dy))

    def __add__(self, other: "Outline") -> "Outline":
        return Outline(self.contours + other.contours)

    def bounds(self):
        pen = BoundsPen(None)
        for contour in self.contours:
            for seg in contour:
                op, pts = seg[0], seg[1:]
                if op == "M":
                    pen.moveTo(pts[0])
                elif op == "L":
                    pen.lineTo(pts[0])
                elif op == "Q":
                    pen.qCurveTo(*pts)
                elif op == "C":
                    pen.curveTo(*pts)
            pen.closePath()
        return pen.bounds

    def svg(self, prec: int = 0) -> str:
        parts = []
        for contour in self.contours:
            for seg in contour:
                op, pts = seg[0], seg[1:]
                parts.append(op + " ".join(f"{num(x, prec)} {num(y, prec)}" for x, y in pts))
            parts.append("Z")
        return "".join(parts)


def polygon(points: list[Point]) -> Outline:
    return Outline([[("M", points[0])] + [("L", p) for p in points[1:]]])


def num(v: float, prec: int) -> str:
    s = f"{round(v, prec):.{prec}f}"
    if "." in s:
        s = s.rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


class _RecordPen(BasePen):
    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.contours: list[list[tuple]] = []

    def _moveTo(self, p):
        self.contours.append([("M", p)])

    def _lineTo(self, p):
        self.contours[-1].append(("L", p))

    def _qCurveToOne(self, a, b):
        self.contours[-1].append(("Q", a, b))

    def _curveToOne(self, a, b, c):
        self.contours[-1].append(("C", a, b, c))

    def _closePath(self):
        # Drop an explicit closing line back to the start point.
        c = self.contours[-1]
        if len(c) > 1 and c[-1][0] == "L" and c[-1][1] == c[0][1]:
            c.pop()

    _endPath = _closePath


@dataclass
class Font:
    tt: TTFont
    glyphs: object
    cmap: dict
    hb_font: hb.Font

    @classmethod
    def load(cls, path: Path, weight: int) -> "Font":
        tt = instancer.instantiateVariableFont(TTFont(path), {"wght": weight})
        buf = io.BytesIO()
        tt.flavor = None
        tt.save(buf)
        tt = TTFont(io.BytesIO(buf.getvalue()))
        hb_font = hb.Font(hb.Face(hb.Blob(buf.getvalue())))
        return cls(tt, tt.getGlyphSet(), tt.getBestCmap(), hb_font)

    def glyph(self, name: str) -> Outline:
        pen = _RecordPen(self.glyphs)
        self.glyphs[name].draw(pen)
        return Outline(pen.contours)

    def char(self, ch: str) -> Outline:
        return self.glyph(self.cmap[ord(ch)])

    def advance(self, ch: str) -> float:
        return self.glyphs[self.cmap[ord(ch)]].width

    def shape(self, text: str, size: float) -> tuple[Outline, float]:
        """Shape text with HarfBuzz (kerning included); return outline at `size` px and width."""
        buf = hb.Buffer()
        buf.add_str(text)
        buf.guess_segment_properties()
        hb.shape(self.hb_font, buf, {"kern": True, "liga": True})
        order = self.tt.getGlyphOrder()
        upm = self.tt["head"].unitsPerEm
        k = size / upm
        out, x = Outline(), 0.0
        for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
            g = self.glyph(order[info.codepoint])
            ox, oy = x + pos.x_offset, pos.y_offset
            out += g.map(lambda p, ox=ox, oy=oy: ((p[0] + ox) * k, (p[1] + oy) * k))
            x += pos.x_advance
        return out, x * k


GEIST_FONT = Font.load(GEIST, WEIGHT)


def stem_width(font: Font = GEIST_FONT) -> float:
    """Width of the d's ascender stem: the two outline points at the ascender."""
    xs = [seg[-1][0] for c in font.char("d").contours for seg in c if seg[-1][1] == ASCENDER]
    return max(xs) - min(xs)


def slash_angle(font: Font = GEIST_FONT) -> float:
    """Angle from vertical of the v's right arm, so the slash runs parallel to it."""
    pts = [seg[-1] for c in font.char("v").contours for seg in c]
    bottom = max((p for p in pts if p[1] == 0), key=lambda p: p[0])
    top = max(pts, key=lambda p: (p[1], p[0]))
    return math.atan2(top[0] - bottom[0], top[1] - bottom[1])


STEM = stem_width()
ANGLE = slash_angle()


def slash(left_at_baseline: float, bottom: float = 0.0, top: float = ASCENDER,
          run: float | None = None, angle: float | None = None) -> Outline:
    """A parallelogram with horizontal cuts; `left_at_baseline` is where its left edge meets y=0."""
    run = STEM * SLASH_RUN if run is None else run
    t = math.tan(ANGLE if angle is None else angle)
    lx = lambda y: left_at_baseline + y * t  # noqa: E731
    return polygon([(lx(bottom), bottom), (lx(top), top), (lx(top) + run, top), (lx(bottom) + run, bottom)])


# --------------------------------------------------------------------------
# Logo geometry
# --------------------------------------------------------------------------

def wordmark(font: Font = GEIST_FONT, slash_bottom: float = 0.0,
             font_slash: bool = False) -> tuple[Outline, Outline]:
    """`div` and its slash in font units, y up, origin at the d's baseline.

    The keyword arguments only exist to draw the alternatives in preview.html.
    """
    ink, x, v_x = Outline(), 0.0, 0.0
    for ch in "div":
        ink += font.char(ch).moved(x)
        if ch == "v":
            v_x = x
        x += font.advance(ch) + TRACK.get(ch, 0)
    if font_slash:
        return ink, font.char("/").moved(x - 30)
    v_pts = [seg[-1] for c in font.char("v").contours for seg in c]
    v_right_at_base = max(p[0] for p in v_pts if p[1] == 0)
    return ink, slash(v_x + v_right_at_base + SLASH_GAP, bottom=slash_bottom,
                      run=stem_width(font) * SLASH_RUN, angle=slash_angle(font))


def mark() -> tuple[Outline, Outline]:
    """`d/` for the icon, in font units, y up."""
    d = GEIST_FONT.char("d")
    stem_right = max(seg[-1][0] for c in d.contours for seg in c)
    return d, slash(stem_right + MARK_GAP)


def union_bounds(*outlines: Outline):
    bs = [o.bounds() for o in outlines]
    return (min(b[0] for b in bs), min(b[1] for b in bs), max(b[2] for b in bs), max(b[3] for b in bs))


def to_svg_space(outlines, prec=0):
    """Flip to y-down with the tight bounding box at the origin, snapped to whole units."""
    x0, y0, x1, y1 = union_bounds(*outlines)
    left, top = math.floor(x0), math.ceil(y1)
    w, h = math.ceil(x1) - left, top - math.floor(y0)
    f = lambda p: (p[0] - left, top - p[1])  # noqa: E731
    return [o.map(f) for o in outlines], w, h


def svg_doc(w: float, h: float, body: str, label: str = "Div", extra: str = "") -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {num(w, 2)} {num(h, 2)}" '
        f'role="img" aria-label="{label}"{extra}>\n<title>{label}</title>\n{body}</svg>\n'
    )


def path(d: str, fill: str, extra: str = "") -> str:
    return f'<path fill="{fill}"{extra} d="{d}"/>\n'


# --------------------------------------------------------------------------
# Icon tile: a rounded square with smoothed (continuous-curvature) corners
# --------------------------------------------------------------------------

def squircle(x: float, y: float, w: float, h: float, r: float, s: float, prec: int = 2) -> str:
    """Rounded rectangle with Figma-style corner smoothing, as SVG path data.

    Each corner is a cubic Bezier into a shortened circular arc and back out,
    so the curvature ramps up from the straight edge instead of jumping.
    """
    p = min((1 + s) * r, w / 2, h / 2)
    arc = 90 * (1 - s)
    arc_len = math.sin(math.radians(arc / 2)) * r * math.sqrt(2)
    alpha = (90 - arc) / 2
    p3p4 = r * math.tan(math.radians(alpha / 2))
    beta = math.radians(45 * s)
    c = p3p4 * math.cos(beta)
    d = c * math.tan(beta)
    b = (p - arc_len - c - d) / 3
    a = 2 * b
    n = lambda v: num(v, prec)  # noqa: E731

    def corner(ux, uy, vx, vy):
        # u: direction along the incoming edge, v: direction of the outgoing edge.
        q = lambda du, dv: (du * ux + dv * vx, du * uy + dv * vy)  # noqa: E731
        c1 = [q(a, 0), q(a + b, 0), q(a + b + c, d)]
        arc_end = q(arc_len, arc_len)
        c2 = [q(d, c), q(d, b + c), q(d, a + b + c)]
        c1s = " ".join(f"{n(px)} {n(py)}" for px, py in c1)
        c2s = " ".join(f"{n(px)} {n(py)}" for px, py in c2)
        return f"c{c1s}a{n(r)} {n(r)} 0 0 1 {n(arc_end[0])} {n(arc_end[1])}c{c2s}"

    return (
        f"M{n(x + p)} {n(y)}H{n(x + w - p)}" + corner(1, 0, 0, 1)
        + f"V{n(y + h - p)}" + corner(0, 1, -1, 0)
        + f"H{n(x + p)}" + corner(-1, 0, 0, -1)
        + f"V{n(y + p)}" + corner(0, -1, 1, 0) + "Z"
    )


