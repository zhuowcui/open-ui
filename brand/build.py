def contrast(a: str, b: str) -> float:
    """WCAG 2 contrast ratio of two #RRGGBB colors."""
    def lum(h):
        def ch(v):
            v = int(v, 16) / 255
            return v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4
        r, g, bl = ch(h[1:3]), ch(h[3:5]), ch(h[5:7])
        return 0.2126 * r + 0.7152 * g + 0.0722 * bl
    hi, lo = sorted((lum(a), lum(b)), reverse=True)
    return (hi + 0.05) / (lo + 0.05)


def inline(svg: str) -> str:
    """An SVG document as inline HTML markup."""
    return svg.replace("<title>Div</title>" + chr(10), "")


def data_uri_png(img: skia.Image) -> str:
    import base64
    return "data:image/png;base64," + base64.b64encode(png_bytes(img)).decode()


def clear_space_svg() -> str:
    """The wordmark with its clear space (one x-height on every side) drawn around it."""
    (letters, sl), w, h = to_svg_space(list(wordmark()))
    m = X_HEIGHT
    f = lambda p: (p[0] + m, p[1] + m)  # noqa: E731
    W, H = w + 2 * m, h + 2 * m
    guide = 'fill="none" stroke="#266EFB" stroke-width="5" stroke-dasharray="18 14"'
    body = (
        f'<rect x="2.5" y="2.5" width="{num(W - 5, 1)}" height="{num(H - 5, 1)}" {guide}/>\n'
        f'<rect x="{num(m, 1)}" y="{num(m, 1)}" width="{w}" height="{h}" fill="none" stroke="#A1A1AA" stroke-width="3"/>\n'
        f'<rect x="{num(m, 1)}" y="0" width="{num(m * 0.42, 1)}" height="{num(m, 1)}" fill="#266EFB" fill-opacity="0.12"/>\n'
        + path(letters.map(f).svg(1), "currentColor") + path(sl.map(f).svg(1), ACCENT)
    )
    return inline(svg_doc(W, H, body))


