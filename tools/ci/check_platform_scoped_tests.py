#!/usr/bin/env python3
"""Keep the Windows-pending Linux-oracle tests explicit and exact.

A test whose expected value comes from the Linux Chromium oracle, its FreeType
raster or its Fontconfig font resolution is marked

    #[cfg_attr(not(target_os = "linux"), ignore = "linux-oracle: <reason>")]

It still compiles everywhere and still runs on Linux. This check requires the
marked set to equal the committed ledger, so no test silently stops running on
another platform and no marker can weaken the Linux gate.
"""

from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[2]
SOURCES = ROOT / "bindings/rust"
LEDGER = ROOT / "docs/v02/generated/windows-pending-tests.txt"
HEADER = (
    "# Tests ignored outside Linux because their expected values come from the\n"
    "# Linux Chromium oracle, FreeType raster or Fontconfig resolution.\n"
    "# Generated by tools/ci/check_platform_scoped_tests.py --write; do not edit.\n"
)
MARKER = re.compile(
    r'#\[cfg_attr\(\s*not\(\s*target_os\s*=\s*"linux"\s*\)\s*,\s*'
    r'ignore\s*=\s*"linux-oracle:\s*([^"]+?)\s*"\s*\)\]'
)
LOOSE = re.compile(r"linux-oracle:")
FUNCTION = re.compile(r"\bfn\s+([A-Za-z_][A-Za-z0-9_]*)")
# Attributes and comments that may separate a marker from its function.
ATTRIBUTES = re.compile(r"(?:\s+|#\[(?:[^\[\]]|\[[^\[\]]*\])*\]|//[^\n]*)*")


def marked_tests(root: Path = SOURCES, base: Path = ROOT) -> tuple[dict[str, str], list[str]]:
    """Map `path::function` to its reason, and report malformed markers.

    Markers are matched across the whole file because rustfmt wraps long
    attributes over several lines.
    """
    tests: dict[str, str] = {}
    errors: list[str] = []
    for path in sorted(root.rglob("*.rs"), key=lambda item: item.relative_to(root).parts):
        parts = path.relative_to(root).parts
        if "vendor" in parts or "target" in parts:
            continue
        text = path.read_text(encoding="utf-8")
        if not LOOSE.search(text):
            continue
        relative = path.relative_to(base).as_posix()
        markers = list(MARKER.finditer(text))
        for match in LOOSE.finditer(text):
            if not any(marker.start() <= match.start() < marker.end() for marker in markers):
                line = text.count("\n", 0, match.start()) + 1
                errors.append(f"{relative}:{line}: malformed linux-oracle marker")
        for marker in markers:
            line = text.count("\n", 0, marker.start()) + 1
            after = ATTRIBUTES.match(text, marker.end())
            function = FUNCTION.match(text, after.end())
            if not function:
                errors.append(f"{relative}:{line}: marker is not attached to a function")
                continue
            # The attribute lines directly above the marker, plus those after it.
            above = text[:marker.start()].split("\n")[:-1]
            preceding = []
            for previous in reversed(above):
                if not previous.strip().startswith(("#[", "//")):
                    break
                preceding.append(previous)
            block = "\n".join(preceding) + text[marker.end():after.end()]
            if not re.search(r"#\[test\]", block):
                errors.append(f"{relative}:{line}: marker is not on a #[test] function")
                continue
            name = f"{relative}::{function.group(1)}"
            if name in tests:
                errors.append(f"{relative}:{line}: duplicate test name {function.group(1)}")
                continue
            tests[name] = " ".join(marker.group(1).split())
    return tests, errors


def render(tests: dict[str, str]) -> str:
    return HEADER + "".join(f"{name}\t{reason}\n" for name, reason in sorted(tests.items()))


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--write", action="store_true", help="rewrite the ledger")
    args = parser.parse_args(argv)
    tests, errors = marked_tests()
    for error in errors:
        print(f"error: {error}", file=sys.stderr)
    if errors:
        return 1
    expected = render(tests)
    if args.write:
        LEDGER.write_bytes(expected.encode("utf-8"))
        print(f"windows-pending tests: {len(tests)} written")
        return 0
    actual = LEDGER.read_bytes().decode("utf-8") if LEDGER.is_file() else ""
    if actual != expected:
        recorded = {
            line.split("\t", 1)[0]
            for line in actual.splitlines()
            if line and not line.startswith("#")
        }
        print(
            "error: windows-pending ledger drift: "
            f"unrecorded={sorted(set(tests) - recorded)} stale={sorted(recorded - set(tests))}",
            file=sys.stderr,
        )
        return 1
    print(f"windows-pending tests: {len(tests)} recorded, ledger exact")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
