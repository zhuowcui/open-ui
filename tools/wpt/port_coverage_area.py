#!/usr/bin/env python3
"""Port one WPT CSS area into a separate coverage suite.

A coverage suite measures an area the expanded census does not include. It
reuses the porter's deterministic Ahem profile, but keeps its own Rust module,
HTML templates and ID manifest, so the census manifests, the mapping CSV and
the census templates stay unchanged.

Usage:
  python tools/wpt/port_coverage_area.py css-grid css_grid
  python tools/wpt/port_coverage_area.py --check css-grid css_grid

Outputs:
  bindings/rust/pixel-compare/src/wpt/wpt_<module>/mod.rs and part_<n>.rs
  tools/coverage/<module>/templates.json
  tools/coverage/<module>/manifest.json   (sorted test IDs)
  tools/coverage/<module>/port-report.json (counts and reasons per file)

``--check`` regenerates everything in memory and fails if any output differs.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
ROOT = SCRIPT_DIR.parents[1]
sys.path.insert(0, str(SCRIPT_DIR))
import port_wpt  # noqa: E402
import splice_text_port  # noqa: E402

RUST_WPT_DIR = ROOT / "bindings/rust/pixel-compare/src/wpt"
COVERAGE_DIR = ROOT / "tools/coverage"
# As the census porter, skip support files, crash tests and tentative specs.
SKIPPED_DIRS = {"support", "resources", "crashtests", "tentative"}
FONT_LIST = re.compile(r"FontFamilyList \{ families: vec!\[[^\]]*\] \}")
EXTENSIONS = (".html", ".htm", ".xht", ".xhtml")
SIGNATURE = "fn(ViewportMetrics) -> Result<Engine, EngineError>"
# Each generated part stays well under GitHub's 50 MB file warning.
PART_BYTES = 16 * 1024 * 1024
HEADER = [
    "//! Auto-generated by tools/wpt/port_coverage_area.py",
    "//! DO NOT EDIT MANUALLY",
    "",
]


def wpt_css_root() -> Path:
    return Path(
        os.path.expanduser(
            os.environ.get(
                "CHROMIUM_WPT_CSS",
                "~/chromium/src/third_party/blink/web_tests/external/wpt/css",
            )
        )
    )


def area_files(base: Path) -> list[Path]:
    files = []
    for root, dirs, names in os.walk(base):
        dirs[:] = sorted(d for d in dirs if d not in SKIPPED_DIRS)
        for name in sorted(names):
            if name.endswith(EXTENSIONS):
                files.append(Path(root) / name)
    return sorted(files, key=lambda path: path.relative_to(base).as_posix())


def unique_name(base: Path, path: Path) -> str:
    relative = path.relative_to(base).as_posix()
    return Path(relative.replace("/", "_")).stem


def port_one(path: Path, module: str, name: str) -> tuple[str, str] | str:
    """Return (rust, template) for a portable file, or the reason it is not."""
    port_wpt.set_porter_profile(
        port_wpt.PorterProfile.DETERMINISTIC_AHEM, retain_text=True
    )
    port_wpt.set_modern_line_clamp_enabled(False)
    port_wpt.set_paint_layer_emission(False)
    parser = port_wpt.parse_wpt_html(str(path))
    root_aware = False
    if splice_text_port.requires_distinct_root_box(parser):
        root_aware = True
        parser = port_wpt.parse_wpt_html(str(path), root_aware=True)
    portable, reason = port_wpt.analyze_portability(parser)
    if not portable:
        return reason
    if not port_wpt.has_layout_content(parser):
        return "no_layout_content"
    fn_name = f"{module}_{port_wpt.sanitize_fn_name(name)}"
    rust = port_wpt.generate_rust_fn(
        fn_name, parser.root, parser.html_styles, root_aware=root_aware
    )
    # The module is exempt from rustfmt, as the census modules are. Leaving
    # the porter's text unformatted keeps the output identical on every host.
    rust = rust.rstrip("\n")
    template = port_wpt.generate_html_template(str(path), root_aware=root_aware)
    return rust, template


def part_source(module: str, part: int, builders: list[tuple[str, str, str]]) -> str:
    """One generated part: its builders, font helpers and registry."""
    body = []
    for test_id, _, rust in builders:
        body.append(f"// Source: {test_id.split('/', 2)[2]}")
        body.append(rust)
        body.append("")
    # Every node repeats the deterministic font list. Each distinct list is
    # built once by a helper, which keeps the generated source a third smaller.
    font_lists: dict[str, str] = {}

    def font_helper(match: re.Match[str]) -> str:
        name = font_lists.setdefault(match.group(0), f"font_families_{len(font_lists)}")
        return f"{name}()"

    text = FONT_LIST.sub(font_helper, "\n".join(body))
    lines = [f"//! WPT coverage tests: {module}, part {part}", *HEADER]
    # Import only the names this part uses, so the build has no warnings.
    used = lambda name: re.search(rf"\b{name}\b", text) is not None  # noqa: E731
    engine = ["Engine", "EngineError"]
    engine += ["NodeHandle as NodeId"] if used("NodeId") else []
    engine += ["RendererNodeState"] if used("RendererNodeState") else []
    geometry = ["Length"] if used("Length") else []
    lines += ["use openui_dom::ElementTag;"] if used("ElementTag") else []
    lines += [
        f"use openui_engine::{{{', '.join(engine)}}};",
        f"use openui_geometry::{{{', '.join(geometry + ['ViewportMetrics'])}}};",
        "use openui_style::*;",
        "",
    ]
    # Root-aware builders start from `root_doc`; import only what is used.
    documents = [name for name in ("base_doc", "root_doc") if f"{name}(" in text]
    if len(documents) == 1:
        lines += [f"use crate::{documents[0]};", ""]
    elif documents:
        lines += [f"use crate::{{{', '.join(documents)}}};", ""]
    for literal, name in font_lists.items():
        lines += [f"fn {name}() -> FontFamilyList {{", f"    {literal}", "}", ""]
    lines.append(text)
    lines.append(f"pub fn registry() -> Vec<(&'static str, {SIGNATURE})> {{")
    lines.append("    vec![")
    for test_id, fn_name, _ in builders:
        lines.append(f'        ("{test_id}", {fn_name} as {SIGNATURE}),')
    lines.append("    ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def module_sources(module: str, builders: list[tuple[str, str, str]]) -> dict[Path, str]:
    """Split the builders into parts of at most PART_BYTES of source each."""
    parts: list[list[tuple[str, str, str]]] = [[]]
    size = 0
    for builder in builders:
        if parts[-1] and size + len(builder[2]) > PART_BYTES:
            parts.append([])
            size = 0
        parts[-1].append(builder)
        size += len(builder[2])
    directory = RUST_WPT_DIR / f"wpt_{module}"
    outputs = {
        directory / f"part_{index}.rs": part_source(module, index, part)
        for index, part in enumerate(parts)
    }
    lines = [f"//! WPT coverage tests: {module}", *HEADER]
    lines += [
        "use openui_engine::{Engine, EngineError};",
        "use openui_geometry::ViewportMetrics;",
        "",
    ]
    lines += [f"mod part_{index};" for index in range(len(parts))]
    lines += [
        "",
        f"pub fn {module}_registry() -> Vec<(&'static str, {SIGNATURE})> {{",
        "    let mut all = Vec::new();",
    ]
    lines += [f"    all.extend(part_{index}::registry());" for index in range(len(parts))]
    lines += ["    all", "}"]
    outputs[directory / "mod.rs"] = "\n".join(lines) + "\n"
    return outputs


def generate(area: str, module: str) -> dict[Path, str]:
    base = wpt_css_root() / area
    if not base.is_dir():
        raise SystemExit(f"missing WPT area: {base}")
    builders: list[tuple[str, str, str]] = []
    templates: dict[str, str] = {}
    not_portable: dict[str, str] = {}
    errors: dict[str, str] = {}
    names: set[str] = set()
    for path in area_files(base):
        name = unique_name(base, path)
        test_id = f"wpt/{module}/{name}"
        if name in names:
            raise SystemExit(f"duplicate coverage test name: {test_id}")
        names.add(name)
        try:
            result = port_one(path, module, name)
        except Exception as error:  # Porter failures are reported, not fatal.
            errors[test_id] = f"{type(error).__name__}: {error}"
            continue
        if isinstance(result, str):
            not_portable[test_id] = result
            continue
        rust, template = result
        fn_name = f"{module}_{port_wpt.sanitize_fn_name(name)}"
        builders.append((test_id, fn_name, rust))
        templates[test_id] = template
    fn_names = [fn_name for _, fn_name, _ in builders]
    if len(fn_names) != len(set(fn_names)):
        raise SystemExit("generated function-name collision")

    ids = sorted(templates)
    report = {
        "schema_version": 1,
        "area": area,
        "module": module,
        "files": len(names),
        "portable": len(ids),
        "not_portable": dict(sorted(not_portable.items())),
        "errors": dict(sorted(errors.items())),
    }
    out_dir = COVERAGE_DIR / module
    dump = lambda value: json.dumps(value, indent=1, sort_keys=True) + "\n"  # noqa: E731
    return {
        **module_sources(module, builders),
        out_dir / "templates.json": dump(templates),
        out_dir / "manifest.json": dump(ids),
        out_dir / "port-report.json": dump(report),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    parser.add_argument("area", help="WPT CSS directory, for example css-grid")
    parser.add_argument("module", help="module name, for example css_grid")
    args = parser.parse_args()
    outputs = generate(args.area, args.module)
    rust_dir = RUST_WPT_DIR / f"wpt_{args.module}"
    stale_parts = sorted(set(rust_dir.glob("*.rs")) - set(outputs))
    if args.check:
        stale = [
            str(path.relative_to(ROOT))
            for path, content in outputs.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ] + [str(path.relative_to(ROOT)) for path in stale_parts]
        if stale:
            print("coverage port is stale: " + ", ".join(stale))
            return 1
        print(f"coverage port {args.module}: current")
        return 0
    for path in stale_parts:
        path.unlink()
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    report = json.loads(outputs[COVERAGE_DIR / args.module / "port-report.json"])
    print(
        f"{args.module}: files={report['files']} portable={report['portable']} "
        f"not_portable={len(report['not_portable'])} errors={len(report['errors'])}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
